local function detectRussian()
	local ok, lang = pcall(function() return tostring(GameSettings.CurrentConfig.Language) end)
	if not ok or lang == nil or lang == "" then return true end
	return string.find(string.lower(lang), "russian", 1, true) ~= nil
end

local strings = detectRussian() and ru or en

function NTMA.L(key, ...)
	local s = strings[key] or en[key] or key
	if select("#", ...) > 0 then return string.format(s, ...) end
	return s
end
